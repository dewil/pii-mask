"""Форматные ПД РФ: regex + контрольные суммы. Валидатор обязателен - без него
любой длинный номер в тексте превращается в ложное срабатывание."""
from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass
class Entity:
    type: str
    text: str
    start: int
    end: int
    key: str  # ключ консистентности: одинаковый key -> одна метка
    # Форма в косвенном падеже: только такую есть смысл заменять леммой при
    # восстановлении. Форматные распознаватели падежей не знают - по умолчанию False.
    oblique: bool = False


# Наши собственные фейки не должны маскироваться повторно
FAKE_PHONE_CODE = "000"
FAKE_EMAIL_RE = re.compile(r"^user\d+@example\.com$", re.IGNORECASE)

PHONE_RE = re.compile(r"(?<!\d)(?:\+7|8)[ \-]?\(?\d{3}\)?[ \-]?\d{3}[ \-]?\d{2}[ \-]?\d{2}(?!\d)")
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}")
TG_RE = re.compile(r"(?<![\w.\-@])@[A-Za-z][A-Za-z0-9_]{4,31}\b")
CARD_RE = re.compile(r"(?<!\d)(?:\d{4}[ \-]?){3}\d{4}(?!\d)")
INN_RE = re.compile(r"(?<!\d)(?:\d{12}|\d{10})(?!\d)")
SNILS_RE = re.compile(r"(?<!\d)\d{3}-\d{3}-\d{3}[ \-]?\d{2}(?!\d)")
PASSPORT_RE = re.compile(r"(?<!\d)\d{4} \d{6}(?!\d)")
PASSPORT_CTX_RE = re.compile(r"паспорт\w*|сери[ия]\w*", re.IGNORECASE)
# Признак того, что документ целиком про удостоверения личности: в таблице слово
# стоит в шапке колонки, а номера тянутся сотнями строк ниже, вне любого окна.
PASSPORT_DOC_CTX_RE = re.compile(
    r"\bДУЛ\b|паспорт\w*|удостоверяющ\w+\s+личность", re.IGNORECASE
)
# ОГРН (13) и ОГРНИП (15) - реквизиты юрлица, а не человека, но в выгрузке или акте
# проверки они однозначно называют организацию, из которой документ. Обезличивание,
# оставившее ОГРН, бессмысленно: номер пробивается в открытом реестре за секунды.
OGRN_RE = re.compile(r"(?<!\d)(?:\d{15}|\d{13})(?!\d)")
# УИД договора (Положение Банка России №758-П) - UUID, иногда с номером части через
# дефис. Сквозной идентификатор сделки: связывает записи между выгрузками и вместе с
# любым внешним источником выводит на конкретного заемщика.
#
# Под тот же шаблон попадает и обычный технический UUID (идентификатор запроса в логе).
# Считаем это приемлемым: для модели такой токен смысла не несет, и лишняя маска
# на нем текст не портит - в отличие от маски на названии инструмента или должности.
#
# Между группами допускается перенос строки: в колоночной верстке (акт, выгрузка
# в PDF) УИД разрывается ровно по дефису, и на первом же прогоне так уехало 780 из
# 1079 вхождений - то есть строгий шаблон пропускал большинство. Один перенос,
# не больше: иначе шаблон начнет склеивать соседние колонки таблицы.
_WRAP = r"[ \t]*\n?[ \t]*"
# Последняя группа необязательна. В колоночной верстке хвост УИД не просто
# переносится на следующую строку - он вообще теряет соседство с головой (pdftotext
# уводит его в другое место страницы). На реальном акте так выглядели 978 вхождений
# из 1079: четыре группы, дефис и обрыв. Голова из 20 шестнадцатеричных знаков
# идентифицирует запись ничуть не хуже целого УИД, поэтому маскируем и ее.
UID_RE = re.compile(
    rf"(?<![\w-])[0-9a-f]{{8}}(?:-{_WRAP}[0-9a-f]{{4}}){{1,3}}"
    rf"(?:-{_WRAP}[0-9a-f]{{12}}(?:-\d{{1,3}})?)?-?(?![\w])",
    re.IGNORECASE,
)
# Разбивка на группы по 4 - не единственная форма записи: извлечение из PDF местами
# теряет внутренние дефисы, и УИД выглядит как "8 знаков - 13 знаков - 1". Ловим
# общую форму и отсеиваем случайное по числу шестнадцатеричных знаков: меньше 16
# подряд идущих - это не идентификатор, а совпадение.
UID_LOOSE_RE = re.compile(r"(?<![\w-])[0-9a-f]{8}-[0-9a-f-]{8,48}(?![\w])", re.IGNORECASE)
_UID_MIN_HEX = 16

# --- Организация: детерминированные формы, которые NER берет через раз ---
#
# Название в кавычках после организационно-правовой формы - самый надежный признак
# организации, какой вообще бывает в русском документе. NER на нем спотыкается не
# из-за самого названия (в изоляции распознает), а из-за верстки: колонки, разрывы
# строк, номера сносок вплотную. На акте проверки так уцелели название банка и два
# бюро - по одному вхождению из десятков, то есть промах случайный и невоспроизводимый.
# Регулярка делает результат детерминированным и заодно дает точные границы спана:
# NER регулярно отрезал закрывающую кавычку.
_ORG_FORM = (
    r"(?:АО|ОАО|ЗАО|ПАО|НАО|ООО|НКО|АНО|ПК|ГК|ФГУП|МУП|ИП"
    r"|Акционерное\s+общество|Публичное\s+акционерное\s+общество"
    r"|Общество\s+с\s+ограниченной\s+ответственностью"
    r"|Банк|Компания|Бюро|Фонд)"
)
# Кавычки бывают не только угловые: извлечение из PDF отдает и прямые ("), а само
# название внутри кавычек верстка рвет переносом ("ПСКОВАГРОПРОМДОР\nСТРОЙ").
ORG_QUOTED_RE = re.compile(
    rf"{_ORG_FORM}[ \t]*\n?[ \t]*[«\"][^»\"]{{2,80}}[»\"]", re.IGNORECASE
)

# Родовые слова в названии организации не опознают ее сами по себе: "бюро",
# "кредитных", "историй" встречаются в тексте акта сотнями раз в обычной речи.
# Разносить по документу имеет смысл только различающие слова.
_ORG_GENERIC = frozenset({
    "банк", "банка", "банку", "бюро", "общество", "компания", "группа", "фонд",
    "кредитных", "историй", "кредитной", "истории", "объединенное", "национальное",
    "коммерческий", "акционерное", "публичное", "российской", "федерации",
    "сервис", "сервисы", "центр", "холдинг", "корпорация", "страховая",
})


def _prefixes(words, minlen: int = 6) -> dict[str, str]:
    """Все обрезки известных слов - обрезок отображается на полное слово.

    Верстка PDF режет содержимое ячейки по ширине колонки: в тексте остаются
    "КОНСТАНТИНОВИ" и "ПСКОВАГРОПРО". У такого куска нет ни одного признака, по
    которому его опознает правило, - но полное слово в документе уже найдено, и
    обрезок от него отличается только хвостом.
    """
    out: dict[str, str] = {}
    for w in words:
        for n in range(minlen, len(w)):
            out.setdefault(w[:n], w)
    return out


def _org_stems(name: str) -> list[str]:
    """Различающие слова названия - по ним оно узнается в изуродованной верстке."""
    words = re.findall(r"[А-ЯЁA-Z][\w-]{2,}", name)
    return [w for w in words if w.lower() not in _ORG_GENERIC]


# --- Реквизиты рядом с ключевым словом ---
#
# Контрольная сумма защищает от ложных срабатываний на произвольном числе, но она же
# отбрасывает настоящий реквизит, набранный с ошибкой или потерявший цифру при
# извлечении текста из PDF. Живой пример: "(ИНН 783199667)" - девять цифр вместо
# десяти, валидатором не берется, а компанию называет ровно так же. Рядом со словом
# "ИНН"/"ОГРН" сомнений в природе числа нет, поэтому здесь контрольная сумма не нужна.
# Регистрационный номер в отраслевом реестре сюда же: в банковском акте "рег. № 1326"
# называет организацию так же однозначно, как ОГРН, - реестр открытый.
# Между словом и числом допускается перенос строки: в PDF карточка организации
# верстается узкой колонкой и рвется где попало ("КПП\n770801001").
REQUISITE_RE = re.compile(
    r"(ИНН|ОГРНИП|ОГРН|КПП|БИК|ОКПО|ОКТМО|ОКВЭД"
    r"|рег(?:истрационный)?\.?[ \t]*(?:номер|№))"
    r"[ \t]*(?:№|:)?[ \t]*\n?[ \t]*(\d{3,15})",
    re.IGNORECASE,
)

# Карточка организации в шапке официального документа - это не одно поле, а десяток,
# и каждое называет ее однозначно: серия и номер свидетельства о регистрации, номера
# лицензий, регистрационный номер в отраслевом реестре. Ключевое слово от числа при
# этом отделено фразой ("Лицензия на осуществление банковских операций №1326"), так
# что правило "слово вплотную к числу" их не берет.
DOC_REQUISITE_RES = (
    # "серия 77 № 007893219" - свидетельство о государственной регистрации
    re.compile(r"сери[яи][ \t\n]*(\d{2,4})[ \t\n]*№?[ \t\n]*(\d{5,9})", re.IGNORECASE),
    # "Лицензия ... №1326", "Свидетельство ... № 309" - фраза между словом и номером
    re.compile(r"(?:лицензи\w+|свидетельств\w+)[^№]{0,120}№[ \t]*(\d[\d-]{2,20})", re.IGNORECASE),
    # "Регистрационный номер кредитной организации, присвоенный ...: 1326"
    re.compile(r"регистрационный[ \t\n]+номер[^:]{0,90}:[ \t\n]*(\d{3,15})", re.IGNORECASE),
)
_REQ_TYPE = {"инн": "INN", "огрн": "OGRN", "огрнип": "OGRN"}


# --- ФИО в формах, которые NER не берет ---
#
# NER обучен на новостях, а в них ФИО пишут обычным регистром. В реестрах, выгрузках
# и таблицах официальных документов они идут КАПСОМ - и распознавание падает почти в
# ноль (замер на акте проверки: из 55 полных ФИО капсом поймано 6). Поэтому такие
# формы ловятся отдельно, регулярками, и работают в том числе с --no-ner.
#
# Якорь везде один - отчество: суффикс отчества дает уверенность, которой нет у пары
# заглавных слов самой по себе ("АКТ ПРОВЕРКИ" - тоже два слова капсом).
_CAPS_WORD = r"[А-ЯЁ]{2,}(?:-[А-ЯЁ]{2,})?"
# Голое "ИЧ" в набор не берем: под него попадают обычные слова капсом (КИРПИЧ,
# ПАРАЛИЧ). Редкие формы вроде "ИЛЬИЧ" закрыты вариантом ЬИЧ.
_PATR_TAIL = r"(?:ОВИЧ|ЕВИЧ|ЬИЧ|ОВНА|ЕВНА|ИЧНА)"
# Полное ФИО капсом: два-три слова, одно из которых - отчество (порядок любой,
# в реестрах встречается и "ФАМИЛИЯ ИМЯ ОТЧЕСТВО", и "ИМЯ ОТЧЕСТВО ФАМИЛИЯ").
# Только в пределах строки: спан через перенос разрезал бы верстку таблицы, а
# оторвавшийся хвост добирается правилом ниже.
_CAPS_PATR = rf"[А-ЯЁ]{{3,}}{_PATR_TAIL}"
# Разделитель слов - пробел или перенос строки (до двух: ячейки в потоке из PDF
# разделены пустой строкой). Ограничение "только в пределах строки" держалось на
# постраничной верстке; в потоковом извлечении ФИО штатно идет по слову на строку,
# и без переносов правило не видит ни одного полного ФИО - остается голое отчество.
_FIO_SEP = r"(?:[ \t]+\n?[ \t]*|\n[ \t]*\n?[ \t]*)"
CAPS_FIO_RE = re.compile(
    rf"(?<![А-ЯЁ\w])(?:"
    # до четырех слов: двойная фамилия ("КОДИЛА КЕНГАНИ ЕКАТЕРИНА ВИТАЛЬЕВНА")
    rf"{_CAPS_WORD}{_FIO_SEP}(?:{_CAPS_WORD}{_FIO_SEP})?{_CAPS_WORD}{_FIO_SEP}{_CAPS_PATR}"
    rf"|{_CAPS_WORD}{_FIO_SEP}{_CAPS_PATR}{_FIO_SEP}{_CAPS_WORD}"  # ИМЯ ОТЧЕСТВО ФАМИЛИЯ
    rf"|{_CAPS_WORD}{_FIO_SEP}{_CAPS_PATR}"                        # ИМЯ ОТЧЕСТВО
    rf")(?![А-ЯЁ\w])"
)
# Одинокое отчество капсом. В колоночной верстке ФИО переносится по словам, и хвост
# оказывается в отдельной строке; оставить его - оставить часть имени.
CAPS_PATR_RE = re.compile(rf"(?<![А-ЯЁ\w])[А-ЯЁ]{{3,}}{_PATR_TAIL}(?![А-ЯЁ\w])")
# "Фамилия И.О." и "И.О. Фамилия" - основная форма подписи в служебных документах.
# NER их тоже пропускает: инициалы с точками рвут сегментацию.
_SURNAME = r"(?:[А-ЯЁ][а-яё]{2,}|[А-ЯЁ]{3,})"
INITIALS_RE = re.compile(
    rf"(?<![А-ЯЁ\w]){_SURNAME}[ \t]+[А-ЯЁ]\.[ \t]?[А-ЯЁ]\.(?!\w)"
    rf"|(?<![А-ЯЁ\w])[А-ЯЁ]\.[ \t]?[А-ЯЁ]\.[ \t]?{_SURNAME}(?![А-ЯЁ\w])"
)

# Сайт компании - такой же идентификатор, как ее название: метка {{ORG_1}} рядом
# с живым доменом работодателя бессмысленна.
URL_SCHEME_RE = re.compile(r"https?://[^\s<>\"'`)\]}]+", re.IGNORECASE)
# Голый домен - только с www. или с делового домена верхнего уровня. Списка вида
# "любой TLD" тут быть не может: ".md" и ".py" - это Молдова и Парагвай, и под
# них попали бы имена файлов вроде core.py и README.md.
BARE_DOMAIN_RE = re.compile(
    r"(?<![@\w./-])(?:www\.[a-z0-9-]+(?:\.[a-z0-9-]+)*"
    r"|[a-z0-9-]+(?:\.[a-z0-9-]+)*\.(?:ru|com|org|net|io|co|biz|info|рф))"
    r"(?![\w@])(?:/[^\s<>\"'`)\]}]*)?",
    re.IGNORECASE,
)
# Технические ссылки персданными не являются - маскировать их значит портить текст.
STOP_HOSTS = frozenset({
    "github.com", "gitlab.com", "bitbucket.org", "stackoverflow.com",
    "python.org", "docs.python.org", "wikipedia.org", "ru.wikipedia.org",
    "habr.com", "example.com", "example.org", "example.net",
})


def _url_host(url: str) -> str:
    host = re.sub(r"^https?://", "", url, flags=re.IGNORECASE).split("/")[0]
    return host.lower().removeprefix("www.")


def digits(s: str) -> str:
    return "".join(c for c in s if c.isdigit())


def luhn_ok(num: str) -> bool:
    total = 0
    for i, c in enumerate(reversed(num)):
        d = int(c)
        if i % 2 == 1:
            d *= 2
            if d > 9:
                d -= 9
        total += d
    return total % 10 == 0


def inn_ok(num: str) -> bool:
    def ctrl(digs: str, koef: list[int]) -> int:
        return sum(int(d) * k for d, k in zip(digs, koef)) % 11 % 10

    if len(num) == 10:
        return ctrl(num[:9], [2, 4, 10, 3, 5, 9, 4, 6, 8]) == int(num[9])
    if len(num) == 12:
        k11 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
        k12 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
        return ctrl(num[:10], k11) == int(num[10]) and ctrl(num[:11], k12) == int(num[11])
    return False


def ogrn_ok(num: str) -> bool:
    """Контрольный разряд ОГРН: остаток от деления числа без последнего разряда
    на 11 (для ОГРНИП - на 13), взятый по модулю 10."""
    if len(num) == 13:
        return int(num[:12]) % 11 % 10 == int(num[12])
    if len(num) == 15:
        return int(num[:14]) % 13 % 10 == int(num[14])
    return False


def snils_ok(num: str) -> bool:
    if len(num) != 11:
        return False
    body, chk = num[:9], int(num[9:])
    s = sum(int(body[i]) * (9 - i) for i in range(9))
    if s < 100:
        expected = s
    elif s in (100, 101):
        expected = 0
    else:
        expected = s % 101
        if expected == 100:
            expected = 0
    return chk == expected


def find_format_entities(text: str) -> list[Entity]:
    out: list[Entity] = []

    for m in EMAIL_RE.finditer(text):
        if not FAKE_EMAIL_RE.match(m.group()):
            out.append(Entity("EMAIL", m.group(), m.start(), m.end(), m.group().lower()))

    for m in TG_RE.finditer(text):
        out.append(Entity("TG", m.group(), m.start(), m.end(), m.group().lower()))

    for rx in (URL_SCHEME_RE, BARE_DOMAIN_RE):
        for m in rx.finditer(text):
            url = m.group().rstrip(".,;:!?")
            if _url_host(url) in STOP_HOSTS:
                continue
            out.append(Entity("URL", url, m.start(), m.start() + len(url), url.lower()))

    for m in PHONE_RE.finditer(text):
        d = digits(m.group())
        if d[1:4] != FAKE_PHONE_CODE:
            out.append(Entity("PHONE", m.group(), m.start(), m.end(), d))

    for m in CARD_RE.finditer(text):
        d = digits(m.group())
        if len(d) == 16 and luhn_ok(d):
            out.append(Entity("CARD", m.group(), m.start(), m.end(), d))

    for m in SNILS_RE.finditer(text):
        d = digits(m.group())
        if snils_ok(d):
            out.append(Entity("SNILS", m.group(), m.start(), m.end(), d))

    for m in INN_RE.finditer(text):
        d = m.group()
        if inn_ok(d):
            out.append(Entity("INN", d, m.start(), m.end(), d))

    for m in REQUISITE_RE.finditer(text):
        num = m.group(2)
        etype = _REQ_TYPE.get(m.group(1).lower(), "REQ")
        # маскируем само число, ключевое слово оставляем: "ИНН {{INN_1}}" читается
        out.append(Entity(etype, num, m.start(2), m.end(2), num))

    for rx in DOC_REQUISITE_RES:
        for m in rx.finditer(text):
            for g in range(1, (m.lastindex or 0) + 1):
                if m.group(g):
                    out.append(Entity("REQ", m.group(g), m.start(g), m.end(g), m.group(g)))

    # Название организации разносится по документу отдельными метками, а не одной:
    # у обрывка в таблице и у полного названия свой original, иначе unmask вернул бы
    # на место полного названия его огрызок. Ровно поэтому же разнос делается только
    # от РЕГУЛЯРКИ (форма плюс кавычки - признак железный), а не от находок NER:
    # одно ложное срабатывание NER, размноженное по документу, портит весь текст.
    quoted: list[tuple[int, int]] = []
    stems: set[str] = set()
    for m in ORG_QUOTED_RE.finditer(text):
        name = m.group()
        quoted.append((m.start(), m.end()))
        stems.update(_org_stems(name))
        out.append(Entity("ORG", name, m.start(), m.end(), " ".join(name.lower().split())))
    stems |= set(_prefixes(stems))
    for stem in stems:
        # Границы считаем по буквам, цифрам и дефису: подчеркивание - разделитель,
        # а не часть слова. Иначе бренд, вклеенный в имя выгрузки
        # ("Эквифакс_уникальные_заявки"), остается в тексте.
        #
        # Короткая аббревиатура разносится только в своем регистре: "ОКБ" - это
        # организация, "окб" в середине слова - случайность. У длинных названий
        # такой опасности нет, там регистр игнорируем (в таблицах пишут капсом).
        flags = re.IGNORECASE if len(stem) > 3 else 0
        bound = r"[^\W_]|-"
        for hit in re.finditer(rf"(?<!{bound}){re.escape(stem)}(?!{bound})", text, flags):
            if any(s <= hit.start() and hit.end() <= e for s, e in quoted):
                continue  # внутри полного названия - там уже есть сущность целиком
            out.append(Entity("ORG", hit.group(), hit.start(), hit.end(), stem.lower()))

    for m in OGRN_RE.finditer(text):
        d = m.group()
        if ogrn_ok(d):
            out.append(Entity("OGRN", d, m.start(), m.end(), d))

    uids: list[tuple[int, int, str]] = []
    for rx in (UID_RE, UID_LOOSE_RE):
        for m in rx.finditer(text):
            if len(re.findall(r"[0-9a-f]", m.group(), re.IGNORECASE)) >= _UID_MIN_HEX:
                uids.append((m.start(), m.end(), m.group()))
    # Два шаблона видят один и тот же номер по-разному: строгий берет только голову,
    # свободный - целиком. Оставляем длинный вариант, вложенный отбрасываем.
    for start, end, txt in uids:
        if any(s <= start and end <= e and (s, e) != (start, end) for s, e, _ in uids):
            continue
        out.append(Entity("UID", txt, start, end, txt.lower()))

    # Окно в 40 знаков работает в связном тексте ("паспорт 4509 123456 выдан"), но не
    # в таблице: там слово стоит один раз в шапке колонки, а номера идут сотнями строк
    # ниже. Поэтому если документ в принципе про документы, удостоверяющие личность,
    # окно расширяется на весь текст. Признак берем строгий - "ДУЛ" или "паспорт" -
    # чтобы одно слово "серия" в накладной не включало режим на весь файл.
    whole_doc = bool(PASSPORT_DOC_CTX_RE.search(text))
    for m in PASSPORT_RE.finditer(text):
        window = text[max(0, m.start() - 40):m.start()]
        if whole_doc or PASSPORT_CTX_RE.search(window):
            out.append(Entity("PASSPORT", m.group(), m.start(), m.end(), digits(m.group())))

    # Полная форма имеет приоритет над одиноким отчеством: отчество внутри уже
    # найденного ФИО отдельной сущностью не выдаем, иначе на выходе два кандидата
    # на один и тот же кусок текста.
    named: list[tuple[int, int]] = []
    fio_words: set[str] = set()
    for rx in (CAPS_FIO_RE, INITIALS_RE):
        for m in rx.finditer(text):
            named.append((m.start(), m.end()))
            out.append(Entity("PERSON", m.group(), m.start(), m.end(),
                              " ".join(m.group().lower().split())))
            if rx is CAPS_FIO_RE:
                fio_words.update(w for w in re.findall(r"[А-ЯЁ-]{4,}", m.group()))
    for m in CAPS_PATR_RE.finditer(text):
        if any(s <= m.start() and m.end() <= e for s, e in named):
            continue
        out.append(Entity("PERSON", m.group(), m.start(), m.end(), m.group().lower()))

    # Фамилия, оставшаяся в строке одна. Поток из PDF рвет ФИО по словам, и на
    # отдельной строке остается "ДРОЗДЕНКО" - ни отчества рядом, ни второго слова,
    # то есть ни одного признака, по которому это имя, а не заголовок. Но полное ФИО
    # с этим же словом в документе уже найдено якорем-отчеством, так что слово
    # известно. Разносим его - строго в том же регистре и только слова от 4 букв:
    # источник детерминированный (см. тот же прием у названий организаций).
    known_fio = {w: w for w in fio_words} | _prefixes(fio_words)
    for hit in re.finditer(r"(?<![А-ЯЁA-Za-zа-яё-])[А-ЯЁ-]{4,}(?![А-ЯЁA-Za-zа-яё-])", text):
        if hit.group() not in known_fio:
            continue
        if any(s <= hit.start() and hit.end() <= e for s, e in named):
            continue
        out.append(Entity("PERSON", hit.group(), hit.start(), hit.end(), hit.group().lower()))

    # Один и тот же спан находят два правила (ИНН - и по контрольной сумме, и по
    # слову рядом). Дубли безвредны для маскировки, но мусорят в выдаче.
    seen: set[tuple[str, int, int]] = set()
    unique = []
    for ent in out:
        mark = (ent.type, ent.start, ent.end)
        if mark not in seen:
            seen.add(mark)
            unique.append(ent)
    return unique
