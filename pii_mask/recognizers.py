"""Форматные ПД РФ: regex + контрольные суммы. Валидатор обязателен - без него
любой длинный номер в тексте превращается в ложное срабатывание."""
from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass
class Entity:
    type: str
    text: str
    start: int
    end: int
    key: str  # ключ консистентности: одинаковый key -> одна метка
    # Форма в косвенном падеже: только такую есть смысл заменять леммой при
    # восстановлении. Форматные распознаватели падежей не знают - по умолчанию False.
    oblique: bool = False
    # Откуда взялась сущность. "dict" - название пришло из словаря организаций, то
    # есть его назвал человек. Такая находка достовернее любой эвристики и на
    # пересечениях побеждает: иначе NER объявляет "Ромашка Россия" персоной и
    # выигрывает по приоритету типа, подменяя ORG на PERSON.
    source: str = ""


# Наши собственные фейки не должны маскироваться повторно
FAKE_PHONE_CODE = "000"
FAKE_EMAIL_RE = re.compile(r"^user\d+@example\.com$", re.IGNORECASE)

PHONE_RE = re.compile(r"(?<!\d)(?:\+7|8)[ \-]?\(?\d{3}\)?[ \-]?\d{3}[ \-]?\d{2}[ \-]?\d{2}(?!\d)")
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}")
TG_RE = re.compile(r"(?<![\w.\-@])@[A-Za-z][A-Za-z0-9_]{4,31}\b")
CARD_RE = re.compile(r"(?<!\d)(?:\d{4}[ \-]?){3}\d{4}(?!\d)")
# Граница не только по цифрам, но и по буквам: артикул товара
# ("OZN7701234567") - не реквизит. Контрольную сумму случайный
# десятизначный номер проходит примерно в одном случае из одиннадцати,
# так что на сотнях артикулов совпадения неизбежны, и отличает настоящий
# ИНН именно то, что он стоит отдельным словом.
INN_RE = re.compile(r"(?<![\w])(?:\d{12}|\d{10})(?![\w])")
SNILS_RE = re.compile(r"(?<!\d)\d{3}-\d{3}-\d{3}[ \-]?\d{2}(?!\d)")
PASSPORT_RE = re.compile(r"(?<!\d)\d{4} \d{6}(?!\d)")
PASSPORT_CTX_RE = re.compile(r"паспорт\w*|сери[ия]\w*", re.IGNORECASE)
# Признак того, что документ целиком про удостоверения личности: в таблице слово
# стоит в шапке колонки, а номера тянутся сотнями строк ниже, вне любого окна.
PASSPORT_DOC_CTX_RE = re.compile(
    r"\bДУЛ\b|паспорт\w*|удостоверяющ\w+\s+личность", re.IGNORECASE
)
# ОГРН (13) и ОГРНИП (15) - реквизиты юрлица, а не человека, но в выгрузке или акте
# проверки они однозначно называют организацию, из которой документ. Обезличивание,
# оставившее ОГРН, бессмысленно: номер пробивается в открытом реестре за секунды.
OGRN_RE = re.compile(r"(?<!\d)(?:\d{15}|\d{13})(?!\d)")
# УИД договора (Положение Банка России №758-П) - UUID, иногда с номером части через
# дефис. Сквозной идентификатор сделки: связывает записи между выгрузками и вместе с
# любым внешним источником выводит на конкретного заемщика.
#
# Под тот же шаблон попадает и обычный технический UUID (идентификатор запроса в логе).
# Считаем это приемлемым: для модели такой токен смысла не несет, и лишняя маска
# на нем текст не портит - в отличие от маски на названии инструмента или должности.
#
# Между группами допускается перенос строки: в колоночной верстке (акт, выгрузка
# в PDF) УИД разрывается ровно по дефису, и на первом же прогоне так уехало 780 из
# 1079 вхождений - то есть строгий шаблон пропускал большинство. Один перенос,
# не больше: иначе шаблон начнет склеивать соседние колонки таблицы.
_WRAP = r"[ \t]*\n?[ \t]*"
# Последняя группа необязательна. В колоночной верстке хвост УИД не просто
# переносится на следующую строку - он вообще теряет соседство с головой (pdftotext
# уводит его в другое место страницы). На реальном акте так выглядели 978 вхождений
# из 1079: четыре группы, дефис и обрыв. Голова из 20 шестнадцатеричных знаков
# идентифицирует запись ничуть не хуже целого УИД, поэтому маскируем и ее.
UID_RE = re.compile(
    rf"(?<![\w-])[0-9a-f]{{8}}(?:-{_WRAP}[0-9a-f]{{4}}){{1,3}}"
    rf"(?:-{_WRAP}[0-9a-f]{{12}}(?:-\d{{1,3}})?)?-?(?![\w])",
    re.IGNORECASE,
)
# Разбивка на группы по 4 - не единственная форма записи: извлечение из PDF местами
# теряет внутренние дефисы, и УИД выглядит как "8 знаков - 13 знаков - 1". Ловим
# общую форму и отсеиваем случайное по числу шестнадцатеричных знаков: меньше 16
# подряд идущих - это не идентификатор, а совпадение.
UID_LOOSE_RE = re.compile(r"(?<![\w-])[0-9a-f]{8}-[0-9a-f-]{8,48}(?![\w])", re.IGNORECASE)
_UID_MIN_HEX = 16

# --- Организация: детерминированные формы, которые NER берет через раз ---
#
# Название в кавычках после организационно-правовой формы - самый надежный признак
# организации, какой вообще бывает в русском документе. NER на нем спотыкается не
# из-за самого названия (в изоляции распознает), а из-за верстки: колонки, разрывы
# строк, номера сносок вплотную. На акте проверки так уцелели название банка и два
# бюро - по одному вхождению из десятков, то есть промах случайный и невоспроизводимый.
# Регулярка делает результат детерминированным и заодно дает точные границы спана:
# NER регулярно отрезал закрывающую кавычку.
_ORG_FORM = (
    r"(?:АО|ОАО|ЗАО|ПАО|НАО|ООО|НКО|АНО|ПК|ГК|ФГУП|МУП|ИП"
    r"|Акционерное\s+общество|Публичное\s+акционерное\s+общество"
    r"|Общество\s+с\s+ограниченной\s+ответственностью"
    r"|Банк|Компания|Бюро|Фонд)"
)
# Та же форма отдельным выражением: нужна, чтобы проверить готовый спан от
# NER на наличие правовой формы (см. Masker.ner_org_needs_form).
ORG_FORM_RE = re.compile(rf"\b{_ORG_FORM}\b", re.IGNORECASE)

# Кавычки бывают не только угловые: извлечение из PDF отдает и прямые ("), а само
# название внутри кавычек верстка рвет переносом ("СТРОЙМОНТАЖНАЛАДКА\nСТРОЙ").
ORG_QUOTED_RE = re.compile(
    rf"{_ORG_FORM}[ \t]*\n?[ \t]*[«\"][^»\"]{{2,80}}[»\"]", re.IGNORECASE
)

# Родовое слово объекта плюс название в кавычках: 'ТРЦ "Ромашка"', 'БЦ "Полевой"'.
# Правовой формы рядом нет, NER такие названия не берет, и место работы остается в
# тексте открытым (досье по опыту, 28.09.2026). В маску уходит только то, что в
# кавычках: родовое слово - тип объекта, а не имя, и без него из документа
# пропадает масштаб работы.
#
# Кавычки сами по себе признаком не являются: в том же документе в них стоят
# "6 в месяц", "до 60" и "уточню". Именем содержимое делает родовое слово перед ним.
_ORG_GENERIC = (
    r"(?:ТРЦ|ТЦ|БЦ|ЖК|МФК|ТПУ|СРО|НИИ|КБ|завод|комбинат|фабрика|агентство"
    r"|холдинг|группа|управление|департамент)"
)
ORG_GENERIC_QUOTED_RE = re.compile(
    rf"(?<![\w-]){_ORG_GENERIC}[ \t]+([«\"][^»\"\n]{{2,80}}[»\"])", re.IGNORECASE
)

# Имя собственное в кавычках без всякого родового слова: в резюме так пишут свои
# проекты и бизнесы (“Zaprosto”, "Кураж+"). Требования жесткие, потому что в
# кавычках чаще стоит не название: каждое слово с заглавной или цифры, не больше
# трех слов. Так отсекаются цитаты и оговорки того же документа - "6 в месяц",
# "до 60", "уточню", «Перевожу с it-технического на человеческий».
ORG_QUOTED_NAME_RE = re.compile(
    r"[«\"“]((?:[A-ZА-ЯЁ][\w.&+-]*|\d[\w.&+-]*)(?:[ \t](?:[A-ZА-ЯЁ][\w.&+-]*|\d[\w.&+-]*)){0,2})[»\"”]")

# Та же форма, но ПОСЛЕ названия и без кавычек: "Василек Технологии, ЗАО".
# Это не экзотика, а основной формат выгрузки резюме с hh.ru - работодатель там
# пишется именно так, - и правило выше его не берет, потому что требует кавычек.
# Промах пойман 18.08.2026 на живом резюме: название работодателя ушло в облачную
# модель открытым текстом, хотя политика услуги обещает замену названий организаций.
#
# Форма только заглавными и только однозначные аббревиатуры. "ИП" сюда не входит:
# после ФИО это чаще указание на предпринимателя-человека, чем хвост названия.
# "Банк", "Компания", "Фонд" тоже не входят - как хвост они слишком часто обычные
# слова ("работал в банке, компания росла").
_ORG_FORM_TRAILING = r"(?:АО|ОАО|ЗАО|ПАО|НАО|ООО|НКО|АНО|ФГУП|ГУП|МУП|ФГБУ)"
# До трех слов названия перед формой. Больше не берем: длинная цепочка заглавных
# слов в колоночной верстке - это соседняя ячейка, а не часть названия.
#
# Хвост "(?![ \t]+[«\"А-ЯЁA-Z])" отсекает случай, когда форма на самом деле ВЕДУЩАЯ
# для следующего названия: в "Москва, ООО Ромашка" организация - "ООО Ромашка", а
# без этой проверки правило забрало бы "Москва, ООО" и замаскировало город вместо
# компании. Проверяем только в пределах строки: перенос после формы нормален
# ("Ромашка, ООО\nАдрес: ...").
ORG_TRAILING_FORM_RE = re.compile(
    r"(?<![\w-])(?:[А-ЯЁA-Z][\w-]*[ \t]+){0,2}[А-ЯЁA-Z][\w-]*"
    rf"[ \t]*,[ \t]*{_ORG_FORM_TRAILING}(?![\w-])(?![ \t]+[«\"А-ЯЁA-Z])"
)

# Родовые слова в названии организации не опознают ее сами по себе: "бюро",
# "кредитных", "историй" встречаются в тексте акта сотнями раз в обычной речи.
# Разносить по документу имеет смысл только различающие слова.
_ORG_GENERIC = frozenset({
    "банк", "банка", "банку", "бюро", "общество", "компания", "группа", "фонд",
    "кредитных", "историй", "кредитной", "истории", "объединенное", "национальное",
    "коммерческий", "акционерное", "публичное", "российской", "федерации",
    "сервис", "сервисы", "центр", "холдинг", "корпорация", "страховая",
})


_PREFIX_MINLEN = 6


def _prefixes(words, minlen: int = _PREFIX_MINLEN) -> dict[str, str]:
    """Все обрезки известных слов - обрезок отображается на полное слово.

    Верстка PDF режет содержимое ячейки по ширине колонки: в тексте остаются
    "КОНСТАНТИНОВИ" и "ПСКОВАГРОПРО". У такого куска нет ни одного признака, по
    которому его опознает правило, - но полное слово в документе уже найдено, и
    обрезок от него отличается только хвостом.
    """
    out: dict[str, str] = {}
    for w in words:
        for n in range(minlen, len(w)):
            out.setdefault(w[:n], w)
    return out


# Граница названия: буквы, цифры и дефис - часть слова, подчеркивание - разделитель.
# Иначе бренд, вклеенный в имя выгрузки ("Эквифакс_уникальные_заявки"), остается
# в тексте. Одна константа на поиск полной фразы и на разнос по словам, чтобы
# граница у них не разъезжалась.
_WORD_CHAR = r"[^\W_]|-"


# Фамилия в латинской транслитерации: русская, украинская, армянская, тюркская
# и грузинская - по суффиксу. Признак дешевый и точный там, где "две заглавные
# подряд" беспомощно: в англоязычном резюме таких пар сотни ("Project Manager",
# "Risk Management", "Distributed Systems"), а суффикса фамилии у них нет.
# Замер 01.10.2026 на 45 живых резюме: 602 пары, из них девять имен - и все
# девять опознаются этим списком.
_LAT_SURNAME_TAIL = (
    "ova", "eva", "yeva", "ina", "yna", "aya", "skaya", "tskaya",
    "ov", "ev", "yev", "in", "yn", "off",
    "sky", "skiy", "skii", "ski", "tsky", "tskiy",
    "enko", "chuk", "yuk", "uk", "yan", "ian", "dze", "shvili", "ets", "its",
    "ko", "ich", "ych", "bek", "baev", "baeva",
)
# Слова, которые сами по себе фамилией не бывают, хотя кончаются похоже:
# "Architecture" (-ure), "Marketing" (-ing) не попадают, а вот "Design",
# "Domain", "Admin", "Certain" ловятся суффиксом -in.
_LAT_NOT_SURNAME = frozenset({
    "design", "domain", "admin", "certain", "main", "plain", "chain", "brain",
    "berlin", "austin", "dublin", "turin", "origin", "margin", "login",
    "within", "again", "spain", "bulletin", "skin", "twin", "basin",
})

_LATIN_PAIR_RE = re.compile(r"(?<![^\W\d_])([A-Z][a-z]{2,})\s+([A-Z][a-z]{2,})(?![^\W\d_])")


def _looks_like_latin_surname(word: str) -> bool:
    low = word.lower()
    if low in _LAT_NOT_SURNAME or len(low) < 4:
        return False
    return low.endswith(_LAT_SURNAME_TAIL)


def find_latin_names(text: str) -> list:
    """Имя человека латиницей: "Ivan Safonov", "Safonov Ivan".

    Порядок слов в резюме встречается любой, поэтому фамилией считаем то слово
    пары, у которого есть транслитерационный суффикс. Оба слова с суффиксом
    (редко, но бывает) - берем пару целиком, это все равно имя.
    """
    out = []
    for m in _LATIN_PAIR_RE.finditer(text):
        первое, второе = m.group(1), m.group(2)
        if " ".join((первое.lower(), второе.lower())) in STOP_TERMS_LOWER():
            continue
        if not (_looks_like_latin_surname(второе) or _looks_like_latin_surname(первое)):
            continue
        out.append(Entity("PERSON", m.group(), m.start(), m.end(),
                          " ".join(m.group().lower().split()), source="latin"))
    return out


def STOP_TERMS_LOWER():
    """Стоп-термины лениво: ner тянет за собой тяжелую морфологию."""
    try:
        from .ner import STOP_TERMS
    except Exception:                                     # noqa: BLE001
        return frozenset()
    return STOP_TERMS


def _org_stems(name: str) -> list[str]:
    """Различающие слова названия - по ним оно узнается в изуродованной верстке."""
    words = re.findall(r"[А-ЯЁA-Z][\w-]{2,}", name)
    return [w for w in words if w.lower() not in _ORG_GENERIC]


def _used_as_common_word(word: str, text: str) -> bool:
    """Слово встречается в этом тексте со строчной буквы, то есть как слово.

    Словаря мало: он знает обычным словом и "Светопись" (это фотография), а в
    документе она - название и больше нигде не встречается. Поэтому второй
    признак берем из самого текста: название пишут с большой буквы, обычное
    слово в середине фразы - с маленькой. Совпали оба признака - слово в этом
    документе работает словом, и разносить его по тексту нельзя.
    """
    if not word[:1].isupper():
        return True
    # Ищем по основе, а не по слову целиком: в названии стоит "Системы", а в
    # тексте то же слово живет в другом падеже ("ремонт систем") или другой
    # частью речи ("Транспортная" - "транспорт данных"). Порог берем тот же, с
    # которого строятся обрезки (_prefixes): проверять надо ровно то, что
    # правило потом разносит по документу, иначе проверка мимо.
    low = word.lower()
    stem = low[:_PREFIX_MINLEN] if len(low) > _PREFIX_MINLEN else low
    return re.search(rf"(?<![^\W\d_]){re.escape(stem)}", text) is not None


def _is_common_word(word: str) -> bool:
    """Слово, которое словарь знает как обычное ("Системы", "Связь", "Гранат").

    Ручной список родовых слов (_ORG_GENERIC) закрывает десяток частых случаев,
    а названий из обычных слов бесконечно много: живые резюме дали "Системы",
    "Связь", "Гранат", "Регион", "Плюс", "Перспектива", "Холдинг". Поэтому
    спрашиваем морфологию - тот же прием и та же причина, что у повторов слов
    названия в core (_org_token_repeats).

    Морфология недоступна (собрано без natasha) - отвечаем "нет" и работаем
    как раньше: это ослабление фильтра, а не отказ разбора.
    """
    try:
        from .ner import NatashaNer
    except Exception:                                     # noqa: BLE001
        return False
    try:
        return NatashaNer.shared().known_common_word(word)
    except Exception:                                     # noqa: BLE001
        return False


# --- Реквизиты рядом с ключевым словом ---
#
# Контрольная сумма защищает от ложных срабатываний на произвольном числе, но она же
# отбрасывает настоящий реквизит, набранный с ошибкой или потерявший цифру при
# извлечении текста из PDF. Живой пример: "(ИНН 783199667)" - девять цифр вместо
# десяти, валидатором не берется, а компанию называет ровно так же. Рядом со словом
# "ИНН"/"ОГРН" сомнений в природе числа нет, поэтому здесь контрольная сумма не нужна.
# Регистрационный номер в отраслевом реестре сюда же: в банковском акте "рег. № 1326"
# называет организацию так же однозначно, как ОГРН, - реестр открытый.
# Между словом и числом допускается перенос строки: в PDF карточка организации
# верстается узкой колонкой и рвется где попало ("КПП\n770801001").
# Одиночная подпись. Часть составной ("КПП/ИНН 997.../770...") сюда попадать не
# должна: слово ИНН там стоит вплотную к ПЕРВОМУ числу, которое на самом деле
# КПП, и шаблон пометил бы чужой номер как ИНН. Составные разбирает
# PAIRED_REQUISITE_RE выше, здесь они отсекаются проверкой соседей по слэшу.
REQUISITE_RE = re.compile(
    r"(?<![/\w])(ИНН|ОГРНИП|ОГРН|КПП|БИК|ОКПО|ОКТМО|ОКВЭД"
    r"|рег(?:истрационный)?\.?[ \t]*(?:номер|№))"
    r"[ \t]*(?:№|:)?[ \t]*\n?[ \t]*(\d{3,15})(?![ \t]*/[ \t]*\d)",
    re.IGNORECASE,
)

# Составная подпись: "ИНН/КПП 6083778353/770101001". Формы пишут реквизиты
# парой, и одиночный шаблон выше такую строку не берет - между словом "ИНН" и
# числом стоит "/КПП". Подписи и числа сопоставляются ПО ПОЗИЦИИ: первое слово
# относится к первому числу. Порядок в парах бывает и обратный ("КПП/ИНН"),
# поэтому по позиции, а не по тому, что "ИНН" встретилось раньше.
_REQ_WORD = r"(?:ИНН|ОГРНИП|ОГРН|КПП|БИК|ОКПО|ОКТМО)"
# Между подписью и числами в бланке стоит уточнение и широкая отбивка колонок
# ("ИНН/КПП продавца        6083778353 / 770101001"), поэтому допускаем прослойку
# без цифр и без перевода строки. Второе значение бывает пустым: у ИП нет КПП, и
# в форме остается висячий слэш.
PAIRED_REQUISITE_RE = re.compile(
    rf"({_REQ_WORD}(?:[ \t]*(?:/|и)[ \t]*{_REQ_WORD})+)"
    rf"[^\d\n]{{0,80}}?"
    rf"(\d{{3,15}}(?:[ \t]*/[ \t]*\d{{0,15}})+)",
    re.IGNORECASE,
)
_SPLIT_LABELS = re.compile(r"[ \t]*(?:/|и)[ \t]*")
_SPLIT_NUMS = re.compile(r"[ \t]*/[ \t]*")


# Ссылка на документ: "Договор МП АБ-11111/24 от 25.01.2023", "Доверенность
# № 63 от 02.12.24", "заявление-оферта № 7777777/23 от 26.02.2023". По такой паре
# номер-дата сделка опознается целиком, поэтому она маскируется вместе с датой.
#
# Правило якорится на СЛОВО, а не на "№": общий реквизит ловит любой номер, и
# среди них номер первичного документа в КУДиР ("№ 4"), без которого книга не
# сверяется с первичкой. Само слово остается в тексте - "Договор {{DOCREF_1}} от
# {{DOCREF_2}}" читается, а документ по нему уже не найти.
_DOC_ANCHOR = (
    r"(?:договор\w*|доверенност\w+|контракт\w*|соглашени\w+|спецификаци\w+"
    r"|заявлени\w+(?:[ \t]*-[ \t]*оферт\w+)?|оферт\w+"
    # Первичные документы: без них в акте оставался открытым номер счета-фактуры.
    r"|сч[её]т[ \t]*-?[ \t]*фактур\w+|сч[её]т\w*|накладн\w+|УПД|УКД"
    r"|акт\w*|платежн\w+[ \t]+поручени\w+)"
)
# Между словом и номером бывает целая формула ("Договору возмездного оказания
# услуг от № ..."), поэтому вставка допускается длинная - но строго без цифр и в
# пределах строки: длинная отбивка колонок означает, что число из соседней графы,
# а не номер договора ("условий Договора            0" - это сумма штрафа).
_DOC_GAP = r"(?:[ \t]{1,3}[А-ЯA-Zа-яa-z][А-ЯA-Zа-яa-z-]{0,19}\.?){0,6}"

# Дата словами: в договорах так пишут чаще, чем цифрами.
_MONTH = (r"(?:январ|феврал|март|апрел|ма|июн|июл|август|сентябр|октябр|ноябр|декабр)"
          r"[а-яё]*")
_DATE = rf"(?:\d{{1,2}}[.\-/]\d{{1,2}}[.\-/]\d{{2,4}}|\d{{1,2}}[ \t]+{_MONTH}[ \t]+\d{{4}}(?:[ \t]+год\w*)?)"

# Дата, стоящая сразу за номером документа ("№ 260 от 01.09.2026"). Нужна
# отдельно от DOCREF_RE: номер бывает найден не своим якорем, а повтором из
# другого места документа, и тогда дата рядом с ним остается открытой. Номер без
# даты сделку не опознает, вместе с датой - опознает.
# Якоря "^" тут быть не должно: match(text, pos) и так привязывает шаблон к
# позиции, а "^" вне MULTILINE совпадает только с началом всей строки - с ним
# правило молча не срабатывало ни разу.
DATE_AFTER_RE = re.compile(rf"[ \t]{{0,3}}от[ \t]{{0,3}}({_DATE})", re.IGNORECASE)

DOCREF_RE = re.compile(
    rf"{_DOC_ANCHOR}{_DOC_GAP}"
    r"[ \t]{0,3}(№|N|N°)?[ \t]{0,3}"
    # Номер берется целиком: без границы токена прослойка откусывает его первые
    # буквы ("Договор МП И" + "Р-11111/24"), и в документе остается огрызок.
    r"(?<![\w-])([A-Za-zА-Яа-я0-9][A-Za-zА-Яа-я0-9\-/._]{1,30})"
    rf"(?:[ \t]{{1,3}}от[ \t]{{1,3}}({_DATE}))?",
    re.IGNORECASE,
)

# Серийный номер сертификата электронной подписи: длинная шестнадцатеричная
# строка рядом с подписантом. Формально не ФИО, но сертификат выдан конкретному
# человеку и опознает его не хуже фамилии.
#
# Порог в 16 знаков и требование смешать буквы с цифрами отсекают и короткие
# коды ("1A2B3C"), и длинные десятичные числа - у последних свой распознаватель,
# и путать их нельзя: сумма в акте это не идентификатор.
CERT_RE = re.compile(r"(?<![0-9A-Za-z])[0-9A-Fa-f]{16,64}(?![0-9A-Za-z])")

# Почтовый адрес. Города и страны шлюз по умолчанию не трогает - в рабочем тексте это
# чаще контекст, чем ПД. Адрес до дома - другое дело: он называет либо место жительства
# человека, либо юридический адрес организации, по которому она находится в открытом
# реестре. Якорь двойной - слово-указатель улицы И номер дома: по отдельности под
# шаблон попадала бы любая пара "существительное плюс число".
_STREET = (
    r"(?:ул|улиц\w+|пр-?кт|проспект\w*|пер|переул\w+|наб|набережн\w+"
    r"|ш|шоссе|б-р|бульвар\w*|пл|площад\w+|прое?зд\w*|туп|тупик\w*)"
)
# Слово-указатель стоит и перед названием ("ул. Каланчевская, д. 27"), и после него
# ("Тверская ул., д. 1") - в реестрах и выписках вторая форма не реже первой.
_ADDR_HEAD = (
    rf"(?:{_STREET}\.?{_WRAP}[А-ЯЁ][\w.-]*(?:{_WRAP}[А-ЯЁа-яё][\w.-]*){{0,3}}"
    rf"|[А-ЯЁ][\w.-]*(?:{_WRAP}[А-ЯЁа-яё][\w.-]*){{0,2}}{_WRAP}{_STREET}\.?)"
)
# Регион и населенный пункт между индексом и улицей: в выгрузке адрес физлица идет
# полной строкой ("640022, Курганская обл., г. Курган, ул. К. Маркса, д.100, кв.67"),
# и без этого куска индекс отрывается от остального адреса.
_ADDR_REGION = rf"(?:[А-ЯЁ][а-яё-]+{_WRAP}(?:обл|край|респ|окр|р-н)\w*\.{{0,2}},?{_WRAP})?"
# Точка после сокращения обязательна: без нее "с" находится внутри слова "Москва"
# и маска съезжает на середину.
_ADDR_CITY = rf"(?:(?<![А-Яа-яЁё])(?:г|гор|пос|пгт|с|дер|город)\.{_WRAP}[А-ЯЁ][а-яё-]+,?{_WRAP})?"
# Городской округ в бланках 1С стоит отдельным звеном перед городом
# ("г.о. Одинцовский, г. Одинцово, ул. ..."). Без него соседние куски адреса
# закрывались, а округ оставался: поле выглядит обезличенным, география в нем
# сохранилась.
_ADDR_DISTRICT = (rf"(?:(?<![А-Яа-яЁё])(?:г\.[ \t]?о\.|городской{_WRAP}округ)"
                  rf"{_WRAP}[А-ЯЁ][а-яё-]+,?{_WRAP})?")
_ADDR_TAIL = (
    rf"д(?:ом)?\.?{_WRAP}\d+[А-Яа-я]?"
    rf"(?:[,\s]*(?:корп|стр|к|с)\w*\.?{_WRAP}\d+[А-Яа-я]?)?"
    rf"(?:[,\s]*кв\w*\.?{_WRAP}\d+)?"
)
ADDRESS_RE = re.compile(
    rf"(?:\d{{6}},?{_WRAP})?{_ADDR_REGION}{_ADDR_DISTRICT}{_ADDR_CITY}"
    rf"(?<![А-Яа-яЁё]){_ADDR_HEAD},?{_WRAP}{_ADDR_TAIL}",
    re.IGNORECASE,
)
# Улица уже могла уехать под другую метку: названия улиц сплошь и рядом даны по
# фамилии, и NER забирает их как персону. Тогда от адреса остается хвост "д.35,
# кв.47" - сам по себе он адрес и есть, потому что пара "дом плюс квартира" другого
# смысла не имеет. Индекс, оторванный версткой от остального, добираем тем же
# правилом: шесть цифр вплотную к региону или городу.
ADDRESS_TAIL_RE = re.compile(
    rf"д(?:ом)?\.?{_WRAP}\d+[А-Яа-я]?[,\s]*кв\w*\.?{_WRAP}\d+", re.IGNORECASE
)
# Между индексом и остальным адресом верстка вклинивает заголовки соседних колонок
# ("540001, Курганская\nпо месту\nобл., г. Курган"), поэтому смотрим не вплотную, а в
# окне. Слово "г." в признаки не берем: в этом же тексте это сокращение года, и по
# нему индексом стало бы любое шестизначное число рядом с датой.
# Адрес целиком от индекса до границы колонки. Шаблоны выше опознают адрес по
# составу ("ул." плюс номер дома) и на формах записи вне их словаря берут только
# индекс - остальное уходит в обезличенный документ открытым, что хуже, чем не
# маскировать вовсе: поле выглядит закрытым. Здесь признак другой и от словаря не
# зависит: индекс с запятой открывает адрес, а закрывает его перевод строки или
# широкая отбивка колонок бланка (три пробела и больше).
ADDRESS_RUN_RE = re.compile(
    r"(?<!\d)\d{6},[ \t]?(?:[^\n]{0,120}?)(?=\n|[ \t]{3,}|$)",
)

ADDRESS_INDEX_RE = re.compile(
    rf"(?<!\d)\d{{6}}(?=,[\s\S]{{0,60}}?"
    rf"(?:обл\.|область|край\b|респ\w*\.|округ|р-н|ул\.|улиц|пр-кт|просп|пер\.|шоссе))",
    re.IGNORECASE,
)

# Карточка организации в шапке официального документа - это не одно поле, а десяток,
# и каждое называет ее однозначно: серия и номер свидетельства о регистрации, номера
# лицензий, регистрационный номер в отраслевом реестре. Ключевое слово от числа при
# этом отделено фразой ("Лицензия на осуществление банковских операций №1326"), так
# что правило "слово вплотную к числу" их не берет.
DOC_REQUISITE_RES = (
    # "серия 77 № 007893219" - свидетельство о государственной регистрации
    re.compile(r"сери[яи][ \t\n]*(\d{2,4})[ \t\n]*№?[ \t\n]*(\d{5,9})", re.IGNORECASE),
    # "Договор №280206/РомашкаБ-И", "Дополнительное соглашение №6". Номер договора не
    # просто идентификатор: в него сплошь и рядом вшит обломок названия стороны
    # ("АльфаБ"), который отдельным словом не стоит и потому не ловится ничем другим.
    re.compile(r"договор\w*[^№]{0,130}№[ \t]*([\w/\-.]+)", re.IGNORECASE),
    re.compile(r"соглашени\w*[^№]{0,130}№[ \t]*([\w/\-.]+)", re.IGNORECASE),
    # "Лицензия ... №1326", "Свидетельство ... № 309" - фраза между словом и номером
    re.compile(r"(?:лицензи\w+|свидетельств\w+)[^№]{0,120}№[ \t]*(\d[\d-]{2,20})", re.IGNORECASE),
    # "Регистрационный номер кредитной организации, присвоенный ...: 1326"
    re.compile(r"регистрационный[ \t\n]+номер[^:]{0,90}:[ \t\n]*(\d{3,15})", re.IGNORECASE),
)
# КПП выделен отдельным типом, а не оставлен в общем REQ: в REQ попадает и
# номер первичного документа ("№ 4"), маскировать который нельзя - без него
# книга не сверяется с первичкой. Включаться КПП должен независимо.
_REQ_TYPE = {"инн": "INN", "огрн": "OGRN", "огрнип": "OGRN", "кпп": "KPP",
             # БИК раньше попадал в общий REQ, а REQ в бухгалтерских документах
             # приходится держать выключенным - под него уходят номера первички.
             # Из-за этого банковский блок счета оставался открытым целиком.
             "бик": "BIK"}

# Номер счета: 20 цифр по якорному слову. Без якоря такое правило брать нельзя -
# двадцатизначным бывает и штрихкод, и внутренний идентификатор выгрузки. С
# якорем ошибиться негде: в бланке рядом со счетом всегда стоит его подпись.
# Длина вынесена из REQUISITE_RE намеренно: там потолок 15 знаков, и счет под
# него не подходил, а поднимать общий потолок значит ловить лишнее другими
# подписями.
ACCOUNT_RE = re.compile(
    r"(?<![/\w])(Сч\.?[ \t]*№?|счет|счёт|р/с|к/с|расч\w*[ \t]+счет\w*"
    r"|корр\w*[ \t]+счет\w*)"
    r"[ \t]*(?:№|:)?[ \t]*\n?[ \t]*(\d{20})(?!\d)",
    re.IGNORECASE,
)


# --- ФИО в формах, которые NER не берет ---
#
# NER обучен на новостях, а в них ФИО пишут обычным регистром. В реестрах, выгрузках
# и таблицах официальных документов они идут КАПСОМ - и распознавание падает почти в
# ноль (замер на акте проверки: из 55 полных ФИО капсом поймано 6). Поэтому такие
# формы ловятся отдельно, регулярками, и работают в том числе с --no-ner.
#
# Якорь везде один - отчество: суффикс отчества дает уверенность, которой нет у пары
# заглавных слов самой по себе ("АКТ ПРОВЕРКИ" - тоже два слова капсом).
_CAPS_WORD = r"[А-ЯЁ]{2,}(?:-[А-ЯЁ]{2,})?"
# Голое "ИЧ" в набор не берем: под него попадают обычные слова капсом (КИРПИЧ,
# ПАРАЛИЧ). Редкие формы вроде "ИЛЬИЧ" закрыты вариантом ЬИЧ.
_PATR_TAIL = r"(?:ОВИЧ|ЕВИЧ|ЬИЧ|ОВНА|ЕВНА|ИЧНА)"
# Полное ФИО капсом: два-три слова, одно из которых - отчество (порядок любой,
# в реестрах встречается и "ФАМИЛИЯ ИМЯ ОТЧЕСТВО", и "ИМЯ ОТЧЕСТВО ФАМИЛИЯ").
# Только в пределах строки: спан через перенос разрезал бы верстку таблицы, а
# оторвавшийся хвост добирается правилом ниже.
_CAPS_PATR = rf"[А-ЯЁ]{{3,}}{_PATR_TAIL}"
# Разделитель слов - пробел или перенос строки (до двух: ячейки в потоке из PDF
# разделены пустой строкой). Ограничение "только в пределах строки" держалось на
# постраничной верстке; в потоковом извлечении ФИО штатно идет по слову на строку,
# и без переносов правило не видит ни одного полного ФИО - остается голое отчество.
_FIO_SEP = r"(?:[ \t]+\n?[ \t]*|\n[ \t]*\n?[ \t]*)"
CAPS_FIO_RE = re.compile(
    rf"(?<![А-ЯЁ\w])(?:"
    # до четырех слов: двойная фамилия ("НКУБА ЗАИМО ЕКАТЕРИНА ВИТАЛЬЕВНА")
    rf"{_CAPS_WORD}{_FIO_SEP}(?:{_CAPS_WORD}{_FIO_SEP})?{_CAPS_WORD}{_FIO_SEP}{_CAPS_PATR}"
    rf"|{_CAPS_WORD}{_FIO_SEP}{_CAPS_PATR}{_FIO_SEP}{_CAPS_WORD}"  # ИМЯ ОТЧЕСТВО ФАМИЛИЯ
    rf"|{_CAPS_WORD}{_FIO_SEP}{_CAPS_PATR}"                        # ИМЯ ОТЧЕСТВО
    rf")(?![А-ЯЁ\w])"
)
# Одинокое отчество капсом. В колоночной верстке ФИО переносится по словам, и хвост
# оказывается в отдельной строке; оставить его - оставить часть имени.
CAPS_PATR_RE = re.compile(rf"(?<![А-ЯЁ\w])[А-ЯЁ]{{3,}}{_PATR_TAIL}(?![А-ЯЁ\w])")
# "Фамилия И.О." и "И.О. Фамилия" - основная форма подписи в служебных документах.
# NER их тоже пропускает: инициалы с точками рвут сегментацию.
_SURNAME = r"(?:[А-ЯЁ][а-яё]{2,}|[А-ЯЁ]{3,})"
INITIALS_RE = re.compile(
    rf"(?<![А-ЯЁ\w]){_SURNAME}[ \t]+[А-ЯЁ]\.[ \t]?[А-ЯЁ]\.(?!\w)"
    rf"|(?<![А-ЯЁ\w])[А-ЯЁ]\.[ \t]?[А-ЯЁ]\.[ \t]?{_SURNAME}(?![А-ЯЁ\w])"
)

# Сайт компании - такой же идентификатор, как ее название: метка {{ORG_1}} рядом
# с живым доменом работодателя бессмысленна.
URL_SCHEME_RE = re.compile(r"https?://[^\s<>\"'`)\]}]+", re.IGNORECASE)
# Голый домен - только с www. или с делового домена верхнего уровня. Списка вида
# "любой TLD" тут быть не может: ".md" и ".py" - это Молдова и Парагвай, и под
# них попали бы имена файлов вроде core.py и README.md.
BARE_DOMAIN_RE = re.compile(
    r"(?<![@\w./-])(?:www\.[a-z0-9-]+(?:\.[a-z0-9-]+)*"
    r"|[a-z0-9-]+(?:\.[a-z0-9-]+)*\.(?:ru|com|org|net|io|co|biz|info|рф))"
    r"(?![\w@])(?:/[^\s<>\"'`)\]}]*)?",
    re.IGNORECASE,
)
# Технические ссылки персданными не являются - маскировать их значит портить текст.
STOP_HOSTS = frozenset({
    "github.com", "gitlab.com", "bitbucket.org", "stackoverflow.com",
    "python.org", "docs.python.org", "wikipedia.org", "ru.wikipedia.org",
    "habr.com", "example.com", "example.org", "example.net",
})


def _url_host(url: str) -> str:
    host = re.sub(r"^https?://", "", url, flags=re.IGNORECASE).split("/")[0]
    return host.lower().removeprefix("www.")


def digits(s: str) -> str:
    return "".join(c for c in s if c.isdigit())


def luhn_ok(num: str) -> bool:
    total = 0
    for i, c in enumerate(reversed(num)):
        d = int(c)
        if i % 2 == 1:
            d *= 2
            if d > 9:
                d -= 9
        total += d
    return total % 10 == 0


def inn_ok(num: str) -> bool:
    def ctrl(digs: str, koef: list[int]) -> int:
        return sum(int(d) * k for d, k in zip(digs, koef)) % 11 % 10

    if len(num) == 10:
        return ctrl(num[:9], [2, 4, 10, 3, 5, 9, 4, 6, 8]) == int(num[9])
    if len(num) == 12:
        k11 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
        k12 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
        return ctrl(num[:10], k11) == int(num[10]) and ctrl(num[:11], k12) == int(num[11])
    return False


def ogrn_ok(num: str) -> bool:
    """Контрольный разряд ОГРН: остаток от деления числа без последнего разряда
    на 11 (для ОГРНИП - на 13), взятый по модулю 10."""
    if len(num) == 13:
        return int(num[:12]) % 11 % 10 == int(num[12])
    if len(num) == 15:
        return int(num[:14]) % 13 % 10 == int(num[14])
    return False


def snils_ok(num: str) -> bool:
    if len(num) != 11:
        return False
    body, chk = num[:9], int(num[9:])
    s = sum(int(body[i]) * (9 - i) for i in range(9))
    if s < 100:
        expected = s
    elif s in (100, 101):
        expected = 0
    else:
        expected = s % 101
        if expected == 100:
            expected = 0
    return chk == expected


# Ник на площадке: "github: raz00mt", "habr: mariap". Опознает человека не хуже
# ника в мессенджере - по нему находится профиль со всей историей, - а ловится
# только якорем: сам по себе это обычное слово.
PROFILE_NICK_RE = re.compile(
    r"\b(?:github|gitlab|bitbucket|habr|behance|dribbble|kaggle|hh|linkedin)"
    r"\s*[:：]\s*([A-Za-z][\w.-]{2,38})", re.IGNORECASE)

# Дата рождения - прямой идентификатор, в отличие от дат опыта работы, которые в
# резюме трогать нельзя (без них документ нечитаем). Различает их только якорь:
# "родилась 26 марта 1997", "Дата рождения: 26.03.1997", "д.р. 26.03.1997".
_МЕСЯЦЫ = ("январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр")
BIRTH_DATE_RE = re.compile(
    r"(?:родил(?:ся|ась)|дата\s+рождения\s*[:\-]?|д\.?\s?р\.?\s*[:\-]?)\s*"
    rf"(\d{{1,2}}[./]\d{{1,2}}[./]\d{{2,4}}|\d{{1,2}}\s+(?:{_МЕСЯЦЫ})\w*\s+\d{{4}})",
    re.IGNORECASE)

# Город проживания в шапке резюме: он про человека, а не про организацию, и в
# связке с узкой должностью сужает круг до единиц. Якорь узкий намеренно -
# город внутри названия компании ("ООО «Екатеринбург-Строй»") не трогаем.
RESIDENCE_RE = re.compile(
    r"(?:проживает|проживание|город проживания|место жительства|город)\s*[:\-]\s*"
    r"([А-ЯЁ][а-яё]+(?:[ -][А-ЯЁ][а-яё]+){0,2})",
    re.IGNORECASE)


def find_format_entities(text: str, org_names: tuple[str, ...] = ()) -> list[Entity]:
    """org_names - названия организаций, заданные снаружи (см. load_org_dict).

    Нужны там, где у названия нет ни кавычек, ни организационно-правовой формы:
    "Ромашка Россия" в резюме опознать нечем - для языковой модели это обычные
    слова. Такие случаи закрываются только тем, что кто-то назвал их явно.
    """
    out: list[Entity] = []

    for m in PROFILE_NICK_RE.finditer(text):
        out.append(Entity("TG", m.group(1), m.start(1), m.end(1),
                          m.group(1).lower(), source="profile"))

    for m in BIRTH_DATE_RE.finditer(text):
        out.append(Entity("DATE", m.group(1), m.start(1), m.end(1),
                          m.group(1).lower(), source="birth"))

    for m in RESIDENCE_RE.finditer(text):
        out.append(Entity("ADDRESS", m.group(1), m.start(1), m.end(1),
                          m.group(1).lower(), source="residence"))

    for m in EMAIL_RE.finditer(text):
        if not FAKE_EMAIL_RE.match(m.group()):
            out.append(Entity("EMAIL", m.group(), m.start(), m.end(), m.group().lower()))

    for m in TG_RE.finditer(text):
        out.append(Entity("TG", m.group(), m.start(), m.end(), m.group().lower()))

    for rx in (URL_SCHEME_RE, BARE_DOMAIN_RE):
        for m in rx.finditer(text):
            url = m.group().rstrip(".,;:!?")
            if _url_host(url) in STOP_HOSTS:
                continue
            out.append(Entity("URL", url, m.start(), m.start() + len(url), url.lower()))

    for m in PHONE_RE.finditer(text):
        d = digits(m.group())
        if d[1:4] != FAKE_PHONE_CODE:
            out.append(Entity("PHONE", m.group(), m.start(), m.end(), d))

    for m in CARD_RE.finditer(text):
        d = digits(m.group())
        if len(d) == 16 and luhn_ok(d):
            out.append(Entity("CARD", m.group(), m.start(), m.end(), d))

    for m in SNILS_RE.finditer(text):
        d = digits(m.group())
        if snils_ok(d):
            out.append(Entity("SNILS", m.group(), m.start(), m.end(), d))

    for m in INN_RE.finditer(text):
        d = m.group()
        if inn_ok(d):
            # "bare" - номер без подписи. Тот же номер рядом со словом "ИНН"
            # найдет REQUISITE_RE и пометит источником "requisite"; строгий
            # режим ядра различает их именно по этой метке, а не по тому,
            # какой распознаватель отработал первым.
            out.append(Entity("INN", d, m.start(), m.end(), d, source="bare"))

    for m in CERT_RE.finditer(text):
        v = m.group()
        if not (any(c.isdigit() for c in v) and any(c.isalpha() for c in v)):
            continue
        out.append(Entity("CERT", v, m.start(), m.end(), v.lower()))

    for m in DOCREF_RE.finditer(text):
        num = m.group(2)
        # Номер обязан содержать цифру: иначе под шаблон попадает продолжение
        # обычной фразы ("по договорам купли-продажи").
        if not any(ch.isdigit() for ch in num):
            continue
        # Без знака номера длинная вставка открывает дорогу ложным срабатываниям:
        # "Договор был заключен на сумму 150000". Поэтому без "№" номер обязан
        # быть непохож на сумму - содержать букву или разделитель.
        if not m.group(1) and num.isdigit():
            continue
        out.append(Entity("DOCREF", num, m.start(2), m.end(2), num.lower(),
                          source="docref"))
        if m.group(3):
            # Дата - отдельный тип: под общей меткой она неотличима от номера, и
            # в реестре непонятно, что во что разворачивать. Тип DATE при этом
            # НЕ означает "маскировать все даты": он появляется только здесь,
            # внутри ссылки на документ (см. test_docref).
            out.append(Entity("DATE", m.group(3), m.start(3), m.end(3),
                              m.group(3), source="docref"))

    for m in PAIRED_REQUISITE_RE.finditer(text):
        labels = _SPLIT_LABELS.split(m.group(1))
        nums = _SPLIT_NUMS.split(m.group(2))
        if len(labels) != len(nums):
            # Подписей и чисел разное количество - сопоставлять наугад нельзя:
            # промах пометил бы КПП как ИНН и наоборот. Пропускаем, одиночный
            # шаблон ниже разберет что сможет.
            continue
        pos = m.start(2)
        for label, num in zip(labels, nums):
            if not num:
                continue        # у ИП нет КПП - в бланке остается пустое место
            start = text.index(num, pos)
            etype = _REQ_TYPE.get(label.strip().lower(), "REQ")
            out.append(Entity(etype, num, start, start + len(num), num,
                              source="requisite"))
            pos = start + len(num)

    for m in REQUISITE_RE.finditer(text):
        num = m.group(2)
        etype = _REQ_TYPE.get(m.group(1).lower(), "REQ")
        # маскируем само число, ключевое слово оставляем: "ИНН {{INN_1}}" читается
        # Помечаем источник: ИНН рядом со словом "ИНН" достовернее голого
        # десятизначного числа, и строгий режим ядра различает их по нему.
        out.append(Entity(etype, num, m.start(2), m.end(2), num, source="requisite"))

    for m in ACCOUNT_RE.finditer(text):
        num = m.group(2)
        out.append(Entity("ACCOUNT", num, m.start(2), m.end(2), num, source="requisite"))

    # Три шаблона видят один адрес по-разному: целиком, хвостом "дом плюс квартира"
    # и одиноким индексом. Вложенные находки отбрасываем, оставляя самую полную.
    addrs = [(m.start(), m.end(), m.group())
             for rx in (ADDRESS_RE, ADDRESS_TAIL_RE, ADDRESS_RUN_RE, ADDRESS_INDEX_RE)
             for m in rx.finditer(text)]
    for start, end, txt in addrs:
        if any(a <= start and end <= b and (a, b) != (start, end) for a, b, _ in addrs):
            continue
        out.append(Entity("ADDRESS", txt, start, end, " ".join(txt.lower().split())))

    for rx in DOC_REQUISITE_RES:
        for m in rx.finditer(text):
            for g in range(1, (m.lastindex or 0) + 1):
                if m.group(g):
                    out.append(Entity("REQ", m.group(g), m.start(g), m.end(g), m.group(g)))

    # Название организации разносится по документу отдельными метками, а не одной:
    # у обрывка в таблице и у полного названия свой original, иначе unmask вернул бы
    # на место полного названия его огрызок. Ровно поэтому же разнос делается только
    # от РЕГУЛЯРКИ (форма плюс кавычки - признак железный), а не от находок NER:
    # одно ложное срабатывание NER, размноженное по документу, портит весь текст.
    quoted: list[tuple[int, int]] = []
    stems: set[str] = set()
    for m in ORG_GENERIC_QUOTED_RE.finditer(text):
        # Спан - только кавычки с названием: группа 1, а не все совпадение.
        out.append(Entity("ORG", m.group(1), m.start(1), m.end(1),
                          m.group(1).strip('«»"').lower()))

    for rx in (ORG_QUOTED_RE, ORG_TRAILING_FORM_RE):
        for m in rx.finditer(text):
            name = m.group()
            if any(s <= m.start() and m.end() <= e for s, e in quoted):
                continue
            quoted.append((m.start(), m.end()))
            stems.update(_org_stems(name))
            out.append(
                Entity("ORG", name, m.start(), m.end(), " ".join(name.lower().split()))
            )

    # Имя в кавычках - последним: сперва правила с правовой формой и родовым
    # словом, а этот кандидат добавляется, только если он не кусок уже
    # найденного названия. Иначе 'АО «Ромашка»' давало бы две сущности, и
    # склонение ниже по тексту цеплялось бы к короткой - с другим ключом.
    for m in ORG_QUOTED_NAME_RE.finditer(text):
        name = m.group(1)
        if len(name) < 3:
            continue
        if any(e.type == "ORG" and e.start <= m.start(1) and m.end(1) <= e.end
               for e in out):
            continue
        out.append(Entity("ORG", name, m.start(1), m.end(1), name.lower()))

    # Словарное название сперва ищется ЦЕЛИКОМ, и только потом разбирается на слова.
    # Порядок здесь - не стиль, а исправление двух дефектов (19.08.2026):
    #   "Ромашка Россия" давала ДВЕ метки вместо одной, потому что от записи
    #   сразу оставались отдельные стемы и каждый искался сам по себе;
    #   записи, у которых нет слов с заглавной буквы ("факультет гуманитарных наук")
    #   или короче трех символов ("VK"), не срабатывали ВООБЩЕ - их молча отсеивала
    #   эвристика стемов, рассчитанная на другое.
    # Найденная фраза занимает спан в quoted, поэтому разнос по словам ниже внутрь
    # нее уже не лезет.
    for name in org_names:
        flags = re.IGNORECASE if len(name) > 3 else 0
        pat = rf"(?<!{_WORD_CHAR}){re.escape(name)}(?!{_WORD_CHAR})"
        for m in re.finditer(pat, text, flags):
            if any(s <= m.start() and m.end() <= e for s, e in quoted):
                continue
            quoted.append((m.start(), m.end()))
            out.append(
                Entity("ORG", m.group(), m.start(), m.end(),
                       " ".join(name.lower().split()), source="dict")
            )

    # Разнос по отдельным словам остается как дополнение: он узнает название в
    # изуродованной верстке, где фраза разорвана переносом или склеена с соседним
    # столбцом.
    for name in org_names:
        stems.update(_org_stems(name))

    # Слово названия, которое словарь знает обычным, разносим только в том виде,
    # в каком оно стоит в названии: "Системы" с большой буквы - это название,
    # "систем" в середине фразы - слово текста. И обрезков от него не делаем:
    # обрезок обычного слова совпадает с другим обычным словом, а смысл обрезка
    # был в том, что сам по себе он ничего не значит.
    #
    # Названия из словаря (org_names) под это правило не подпадают: раз человек
    # назвал организацию явно, закрываем ее везде, включая склонения.
    словарные = {w for name in org_names for w in _org_stems(name)}
    осторожные = {s for s in stems
                  if s not in словарные and _is_common_word(s)
                  and _used_as_common_word(s, text)}
    stems |= set(_prefixes(stems - осторожные))
    for stem in stems:
        # Границы считаем по буквам, цифрам и дефису: подчеркивание - разделитель,
        # а не часть слова. Иначе бренд, вклеенный в имя выгрузки
        # ("Эквифакс_уникальные_заявки"), остается в тексте.
        #
        # Короткая аббревиатура разносится только в своем регистре: "ОКБ" - это
        # организация, "окб" в середине слова - случайность. У длинных названий
        # такой опасности нет, там регистр игнорируем (в таблицах пишут капсом).
        flags = re.IGNORECASE if len(stem) > 3 and stem not in осторожные else 0
        bound = _WORD_CHAR
        for hit in re.finditer(rf"(?<!{bound}){re.escape(stem)}(?!{bound})", text, flags):
            if any(s <= hit.start() and hit.end() <= e for s, e in quoted):
                continue  # внутри полного названия - там уже есть сущность целиком
            out.append(Entity("ORG", hit.group(), hit.start(), hit.end(), stem.lower()))

    out.extend(find_latin_names(text))

    for m in OGRN_RE.finditer(text):
        d = m.group()
        if ogrn_ok(d):
            out.append(Entity("OGRN", d, m.start(), m.end(), d))

    uids: list[tuple[int, int, str]] = []
    for rx in (UID_RE, UID_LOOSE_RE):
        for m in rx.finditer(text):
            if len(re.findall(r"[0-9a-f]", m.group(), re.IGNORECASE)) >= _UID_MIN_HEX:
                uids.append((m.start(), m.end(), m.group()))
    # Два шаблона видят один и тот же номер по-разному: строгий берет только голову,
    # свободный - целиком. Оставляем длинный вариант, вложенный отбрасываем.
    for start, end, txt in uids:
        if any(s <= start and end <= e and (s, e) != (start, end) for s, e, _ in uids):
            continue
        out.append(Entity("UID", txt, start, end, txt.lower()))

    # Окно в 40 знаков работает в связном тексте ("паспорт 4509 123456 выдан"), но не
    # в таблице: там слово стоит один раз в шапке колонки, а номера идут сотнями строк
    # ниже. Поэтому если документ в принципе про документы, удостоверяющие личность,
    # окно расширяется на весь текст. Признак берем строгий - "ДУЛ" или "паспорт" -
    # чтобы одно слово "серия" в накладной не включало режим на весь файл.
    whole_doc = bool(PASSPORT_DOC_CTX_RE.search(text))
    for m in PASSPORT_RE.finditer(text):
        window = text[max(0, m.start() - 40):m.start()]
        if whole_doc or PASSPORT_CTX_RE.search(window):
            out.append(Entity("PASSPORT", m.group(), m.start(), m.end(), digits(m.group())))

    # Полная форма имеет приоритет над одиноким отчеством: отчество внутри уже
    # найденного ФИО отдельной сущностью не выдаем, иначе на выходе два кандидата
    # на один и тот же кусок текста.
    named: list[tuple[int, int]] = []
    fio_words: set[str] = set()
    for rx in (CAPS_FIO_RE, INITIALS_RE):
        for m in rx.finditer(text):
            named.append((m.start(), m.end()))
            out.append(Entity("PERSON", m.group(), m.start(), m.end(),
                              " ".join(m.group().lower().split())))
            if rx is CAPS_FIO_RE:
                fio_words.update(w for w in re.findall(r"[А-ЯЁ-]{4,}", m.group()))
    for m in CAPS_PATR_RE.finditer(text):
        if any(s <= m.start() and m.end() <= e for s, e in named):
            continue
        out.append(Entity("PERSON", m.group(), m.start(), m.end(), m.group().lower()))

    # Фамилия, оставшаяся в строке одна. Поток из PDF рвет ФИО по словам, и на
    # отдельной строке остается "ВЕРШКОВА" - ни отчества рядом, ни второго слова,
    # то есть ни одного признака, по которому это имя, а не заголовок. Но полное ФИО
    # с этим же словом в документе уже найдено якорем-отчеством, так что слово
    # известно. Разносим его - строго в том же регистре и только слова от 4 букв:
    # источник детерминированный (см. тот же прием у названий организаций).
    known_fio = {w: w for w in fio_words} | _prefixes(fio_words)
    for hit in re.finditer(r"(?<![А-ЯЁA-Za-zа-яё-])[А-ЯЁ-]{4,}(?![А-ЯЁA-Za-zа-яё-])", text):
        if hit.group() not in known_fio:
            continue
        if any(s <= hit.start() and hit.end() <= e for s, e in named):
            continue
        out.append(Entity("PERSON", hit.group(), hit.start(), hit.end(), hit.group().lower()))

    # Один и тот же спан находят два правила (ИНН - и по контрольной сумме, и по
    # слову рядом). Дубли безвредны для маскировки, но мусорят в выдаче.
    # При равном спане оставляем находку с более сильным источником: номер,
    # найденный рядом со словом "ИНН", достовернее того же номера, найденного
    # одной контрольной суммой. Раньше побеждал тот, чей распознаватель отработал
    # первым, и подпись терялась - а строгий режим ядра различает их именно по ней.
    rank = {"dict": 3, "requisite": 2, "": 1, "bare": 0}
    best: dict[tuple[str, int, int], Entity] = {}
    order: list[tuple[str, int, int]] = []
    for ent in out:
        mark = (ent.type, ent.start, ent.end)
        if mark not in best:
            best[mark] = ent
            order.append(mark)
        elif rank.get(ent.source, 1) > rank.get(best[mark].source, 1):
            best[mark] = ent
    return [best[m] for m in order]


def load_org_dict(path) -> tuple[str, ...]:
    """Словарь названий организаций: по одному на строку, '#' - комментарий.

    Существует потому, что у части названий нет ни одного формального признака.
    "Ромашка Россия" в строке резюме - для языковой модели обычные слова, и
    добавить их в текст правилом нельзя: любое правило, которое возьмет их, возьмет
    заодно половину документа. Единственный надежный источник тут - человек.

    Словарь не заменяет распознавание, а закрывает его хвост, и он заведомо неполон:
    обещать в документах "маскируем все названия организаций" на этом основании
    нельзя (проверено 18.08.2026 - именно так политика услуги и разошлась с фактом).
    """
    from pathlib import Path

    p = Path(path)
    if not p.is_file():
        raise SystemExit(f"словарь организаций не найден: {p}")
    names = []
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)
    return tuple(names)
