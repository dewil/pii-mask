"""Родовые термины не должны становиться "организациями".

Найдено на живом резюме 13.08.2026: из 50 меток ORG настоящими организациями
были около 15. Остальное - технологии (Jira, MySQL, Ollama), методологии
(Scrum, Kanban, EVM), роли (Product Owner, Team Lead) и аббревиатуры домена
(AI, IT, HR, P&L). Фраза "внедряю AI в процессы" превращалась в "внедряю
{{ORG_2}} в процессы", после чего документ нечитаем ни человеком, ни моделью.

Смысл маскировки ORG - скрыть аффилиации человека, а не вынести из текста
предметную лексику. Поэтому тест держит обе границы сразу: термины остаются,
работодатели исчезают.
"""
import pytest

from pii_mask.core import Masker

# Термины, которые обязаны пережить маскировку дословно.
TERMS = [
    "AI", "IT", "HR", "P&L", "NDA",
    "Scrum", "Kanban", "Waterfall", "EVM",
    "Jira", "Redmine", "MS Project", "MySQL", "Laravel", "Ollama",
    "Product Owner", "Team Lead",
    # составные: хвост после дефиса не меняет сути термина
    "AI-стек", "SDD-конвейер", "P&L-отчетность",
]

# Названия работодателей, которые обязаны исчезнуть.
EMPLOYERS = ["СИБУР", "Авито", "Schlumberger", "Maersk Line"]


@pytest.mark.parametrize("term", TERMS)
def test_term_survives(term):
    # Контекст - строка навыков, как в живом резюме. Искусственная фраза
    # ("Внедряю NDA в процессы") ломает сегментацию: NER склеивает глагол
    # с термином в одну "персону", и падает тест, а не код.
    masked, _ = Masker().mask(
        f"Ключевые навыки: {term}, управление проектами, работа с командой."
    )
    assert term in masked, f"термин {term!r} замаскирован как сущность: {masked!r}"
    assert "ORG" not in masked, f"на {term!r} появилась метка организации: {masked!r}"


@pytest.mark.parametrize("org", EMPLOYERS)
def test_employer_is_masked(org):
    """Обратная граница: стоп-лист не должен глушить маскировку работодателей."""
    masked, _ = Masker().mask(
        f"Руководил программой проектов в компании {org} с 2019 по 2024 год."
    )
    assert org not in masked, f"работодатель {org!r} не замаскирован: {masked!r}"
