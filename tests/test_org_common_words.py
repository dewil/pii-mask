"""Нарицательное слово из названия не закрывает текст целиком.

Название вроде "Системы и Связь" состоит из обычных слов. Разнос по словам и
обрезкам (он нужен, чтобы узнать название в порванной версткой PDF) превращал
их в маску по всему документу: "ремонт {{ORG}} безопасности и инженерных
{{ORG}}". Найдено 30.09.2026 на живых резюме - 8 файлов, около сорока процентов
масок организаций оказались такими обрывками.
"""
from pii_mask.core import Masker

ТЕКСТ = ('Опыт работы\n'
         'ООО "Системы и Связь", 02.2014 - 01.2025\n'
         'Ведущий инженер\n'
         'Что делал: ремонт систем безопасности, обслуживание инженерных систем;\n'
         'наладка связи между объектами.\n')


def mask(text, **kw):
    return Masker(types=("ORG",), ner_org_needs_form=False, **kw).mask(text)[0]


def test_common_word_from_a_name_does_not_mask_the_text():
    out = mask(ТЕКСТ)
    assert "ремонт систем безопасности" in out
    assert "инженерных систем" in out
    assert "наладка связи" in out


def test_the_name_itself_is_still_masked():
    """Ради чего все затевалось: само название закрыто."""
    out = mask(ТЕКСТ)
    assert "Системы и Связь" not in out


def test_capitalised_repeat_of_a_common_word_is_still_masked():
    """"Системы и Связь" отдельной строкой - это название, а не слово текста."""
    out = mask(ТЕКСТ + "Рекомендация от Системы и Связь.\n")
    assert "от Системы и Связь" not in out


def test_invented_name_is_still_spread_over_the_document():
    """Несловарное название разносится как раньше - в том числе обрезком."""
    текст = ('ООО "Светопись", 02.2014 - 01.2025\n'
             'Ведущий инженер\n'
             'Проект для Светописи, отчет Светопи\n')   # хвост срезан версткой
    out = mask(текст)
    assert "Светопись" not in out and "Светописи" not in out
    assert "Светопи\n" not in out


def test_dictionary_name_of_common_words_still_works(tmp_path):
    """Словарь сильнее морфологии: раз название названо, закрываем везде."""
    out = mask("Работал в компании Перспектива, потом в другой.",
               org_names=("Перспектива",))
    assert "Перспектива" not in out
