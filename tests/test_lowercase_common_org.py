"""Обычное слово со строчной буквы - не организация.

На живых резюме (30.09.2026) в маски организаций уходили слова, которыми
говорит сам документ: "зона ответственности - транспорт данных", "баланс
контроль", "в корзину -> куплено", "образование: бакалавриат". Название пишут
с большой буквы, поэтому строчная плюс словарное слово - надежная пара
признаков.
"""
import pytest

from pii_mask.core import Masker


def masked(text):
    return Masker(types=("ORG",), ner_org_needs_form=False).mask(text)[0]


@pytest.mark.parametrize("фраза, слово", [
    ("Зона ответственности - транспорт данных и пользовательские сценарии.", "транспорт"),
    ("Виды работ и баланс контроль по объектам.", "контроль"),
    ('Считала conversion из статуса "Добавлено в корзину" в "куплено".', "куплено"),
    ("Образование: бакалавриат, бизнес-информатика.", "бакалавриат"),
    ("Отчетность для казначейство РФ и смежных ведомств.", "казначейство"),
])
def test_common_word_in_lower_case_is_not_an_organisation(фраза, слово):
    текст = f"Опыт работы\nВедущий аналитик\n{фраза}\nПроекты и задачи.\n"
    assert слово in masked(текст)


def test_a_name_in_lower_case_is_still_caught_by_the_dictionary():
    """Строчная буква не должна прятать название, названное в словаре."""
    out = Masker(types=("ORG",), ner_org_needs_form=False,
                 org_names=("Светопись",)).mask(
        "Работал в светопись два года, потом ушел.")[0]
    assert "светопись" not in out


def test_capitalised_word_is_still_a_candidate():
    """С большой буквы то же слово остается кандидатом в названия."""
    out = masked('Работал в ООО "Контроль", отвечал за качество.')
    assert "Контроль" not in out
